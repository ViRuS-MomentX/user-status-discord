package ru.virus.voicebridge;

import java.util.List;

/**
 * Источник подсказок: что включить после того, что попросили.
 *
 * <p>Каталогов два, потому что они по-разному доступны. Last.fm умеет настоящие
 * похожие песни, но отвечает не отовсюду; iTunes доступен шире, зато понятия
 * «похожие» у него нет вовсе.
 */
public interface MusicCatalog {

    /** Готов ли каталог к работе: у части источников нужен ключ. */
    boolean isConfigured();

    /** Человеку понятное название — для сообщений об ошибках. */
    String name();

    /**
     * Собирает плейлист по тому, что ввёл пользователь.
     *
     * @param limit сколько песен нужно всего
     * @return список от первой к последней; пустой, если ничего не нашлось
     */
    List<Song> playlistFor(String input, int limit);

    /**
     * Песни, популярные прямо сейчас.
     *
     * @return список от самой популярной; пустой, если каталог такого не умеет
     */
    List<Song> trending(int limit);

    /**
     * Песни по общему слову — «christmas», «summer» и тому подобное.
     *
     * <p>В отличие от {@link #playlistFor}, ничего не разгадывает: не пытается понять,
     * исполнитель это или песня, а просто отдаёт подходящее.
     */
    List<Song> byTerm(String term, int limit);

    /**
     * Популярные песни конкретного исполнителя.
     */
    List<Song> byArtist(String artist, int limit);
}
